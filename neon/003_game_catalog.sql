-- Run in Neon SQL Editor before deploying game catalog changes.

begin;

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  provider_game_id integer not null check (provider_game_id > 0),
  room_id integer not null default 1 check (room_id > 0),
  name text not null check (char_length(btrim(name)) between 1 and 80),
  category text not null default 'slots' check (category in ('slots', 'cards', 'buffalo', 'other')),
  image_url text,
  gradient_start text not null default '#5c3918' check (gradient_start ~ '^#[0-9A-Fa-f]{6}$'),
  gradient_end text not null default '#d59612' check (gradient_end ~ '^#[0-9A-Fa-f]{6}$'),
  players_online integer check (players_online is null or players_online >= 0),
  is_popular boolean not null default false,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint games_provider_room_unique unique (provider_game_id, room_id)
);

create index if not exists games_active_order_idx
  on public.games (sort_order, id)
  where is_active = true;

revoke all on public.games from public;

insert into public.games
  (provider_game_id, room_id, name, category, image_url, gradient_start, gradient_end, is_popular, is_active, sort_order)
values
  (23, 1, 'Charge Buffalo', 'buffalo', '/images/buffalo.png', '#5c3918', '#d59612', true, true, 0)
on conflict (provider_game_id, room_id) do nothing;

commit;

select id, provider_game_id, room_id, name, category, is_active
  from public.games
 order by sort_order, id;
